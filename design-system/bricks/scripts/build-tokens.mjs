#!/usr/bin/env node
// BRICKS token generator. Zero dependencies.
// Reads  themes/<theme>/tokens.json  (each must satisfy contract.json)
// Writes generated/bricks.tokens.css, bricks.tokens.ts, bricks.tailwind.css, contrast-report.md
// Usage: node scripts/build-tokens.mjs [packageRoot]
// The theme JSON files are the source of truth. Never hand-edit generated/.

import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(process.argv[2] ?? '.');
const outDir = path.join(root, 'generated');
const contract = JSON.parse(fs.readFileSync(path.join(root, 'contract.json'), 'utf8'));
const prefix = contract.prefix; // "--bricks-"
const MODES = contract.modes; // ["light", "dark"]

// ---------- 1. Load themes ----------
const themeDirs = fs
  .readdirSync(path.join(root, 'themes'), { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(root, 'themes', d.name, 'tokens.json')))
  .map((d) => d.name)
  .sort((a, b) => (a === 'default' ? -1 : b === 'default' ? 1 : a.localeCompare(b))); // default first

const flatten = (json) => {
  const semantic = [];
  const core = [];
  const walk = (tokens, base) => {
    for (const [key, t] of Object.entries(tokens)) semantic.push({ path: [...base, key], ...t });
  };
  for (const [cat, def] of Object.entries(json.categories)) {
    if (cat === 'corePalette') {
      for (const [hue, shades] of Object.entries(def.tokens))
        for (const [shade, t] of Object.entries(shades))
          core.push({ path: [hue, shade], cssVariable: t.cssVariable, value: t.value });
    } else if (def.groups) {
      for (const [g, grp] of Object.entries(def.groups)) walk(grp.tokens, [cat, g]);
    } else {
      walk(def.tokens, [cat]);
    }
  }
  return { semantic, core };
};

const errors = [];
const themes = themeDirs.map((dir) => {
  const json = JSON.parse(fs.readFileSync(path.join(root, 'themes', dir, 'tokens.json'), 'utf8'));
  const meta = json.theme;
  const { semantic, core } = flatten(json);
  const pathKey = (t) => t.path.join('.');
  const byPath = new Map(semantic.map((t) => [pathKey(t), t]));
  const tag = `[${meta.name}]`;

  if (meta.name !== dir) errors.push(`${tag} theme.name must match folder name "${dir}"`);
  if (meta.cssVariablePrefix !== prefix) errors.push(`${tag} prefix must be ${prefix}`);
  if (!meta.disclaimer) errors.push(`${tag} missing theme.disclaimer`);
  for (const p of contract.tokens) if (!byPath.has(p)) errors.push(`${tag} missing contract token ${p}`);

  const defined = new Set([...core.map((c) => c.cssVariable), ...semantic.map((t) => t.cssVariable)]);
  const seen = new Set();
  for (const t of [...semantic, ...core]) {
    if (!t.cssVariable.startsWith(prefix)) errors.push(`${tag} bad prefix ${t.cssVariable}`);
    if (seen.has(t.cssVariable)) errors.push(`${tag} duplicate ${t.cssVariable}`);
    seen.add(t.cssVariable);
  }
  for (const t of semantic) {
    for (const m of MODES) {
      if (!t[m]?.value) errors.push(`${tag} missing ${m} value ${t.cssVariable}`);
      for (const r of (t[m]?.value ?? '').matchAll(/var\((--[\w-]+)\)/g))
        if (!defined.has(r[1])) errors.push(`${tag} unresolved ${r[1]} in ${t.cssVariable}`);
    }
  }
  const contractSet = new Set(contract.tokens);
  const extensions = semantic.filter((t) => !contractSet.has(pathKey(t)));
  return { dir, meta, semantic, core, byPath, extensions };
});

if (!themes.length) errors.push('No themes found in themes/<name>/tokens.json');
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

// ---------- 2. CSS ----------
const banner = `/* GENERATED by scripts/build-tokens.mjs from themes/<name>/tokens.json. Do not edit by hand. */\n`;
const decl = (v, val) => `  ${v}: ${val};`;
const themeSel = (name, mode) => {
  const base = mode ? `[data-theme="${name}"][data-mode="${mode}"]` : `[data-theme="${name}"]`;
  if (name !== 'default') return base;
  // The default theme also applies when no data-theme attribute is set.
  const fallback = mode ? `:root:not([data-theme])[data-mode="${mode}"]` : ':root:not([data-theme])';
  return `${fallback},\n${base}`;
};

let css = banner + `/* Switching: <html data-theme="default|bluefield|..." data-mode="light|dark">. Light is the default mode. */\n`;
for (const th of themes) {
  css += `\n/* ===== ${th.meta.label} (${th.meta.name}) =====\n   ${th.meta.disclaimer}\n   Source: ${th.meta.source} */\n`;
  css += `${themeSel(th.meta.name)} {\n  color-scheme: light;\n`;
  css += th.core.map((c) => decl(c.cssVariable, c.value)).join('\n') + '\n';
  css += th.semantic.map((t) => decl(t.cssVariable, t.light.value)).join('\n') + '\n}\n\n';
  css += `${themeSel(th.meta.name, 'dark')} {\n  color-scheme: dark;\n`;
  css += th.semantic.map((t) => decl(t.cssVariable, t.dark.value)).join('\n') + '\n}\n';
}

// ---------- 2b. Typography ----------
const typoPath = path.join(root, 'typography.json');
const scale = fs.existsSync(typoPath) ? JSON.parse(fs.readFileSync(typoPath, 'utf8')).styles : {};
const ROLES = ['display', 'highlight', 'heading', 'label', 'body'];
const kebab = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const dim = (d) => (d.unit === 'px' ? `${d.value}px` : `${d.value}em`);
let typeCss = `\n/* ===== Typography =====\n   Per theme: font families and per-role weight/style. Theme independent: the type scale classes below. */\n`;
for (const th of themes) {
  const ty = th.meta.typography;
  if (!ty) continue;
  const lines = [];
  for (const [r, f] of Object.entries(ty.families)) lines.push(decl(`${prefix}font-${r}`, f.stack));
  for (const r of ROLES) lines.push(decl(`${prefix}font-weight-${r}`, String(ty.weights[r].weight)), decl(`${prefix}font-style-${r}`, ty.weights[r].style));
  typeCss += `${themeSel(th.meta.name)} {\n${lines.join('\n')}\n}\n`;
}
const famVar = { display: 'display', highlight: 'highlight', body: 'body', mono: 'mono' };
const fixedWeight = (e) => `  font-weight: ${e.weight};\n  font-style: ${e.style};`;
let scaleCss = '';
for (const e of Object.values(scale)) {
  const cls = `.bricks-text-${kebab(e.group)}-${kebab(e.step)}`;
  const w = e.weightSource === 'fixed' ? fixedWeight(e) : `  font-weight: var(${prefix}font-weight-${e.weightSource});\n  font-style: var(${prefix}font-style-${e.weightSource});`;
  scaleCss += `${cls} {\n  font-family: var(${prefix}font-${famVar[e.family]});\n${w}\n  font-size: ${e.fontSize}px;\n  line-height: ${dim(e.lineHeight)};\n  letter-spacing: ${dim(e.letterSpacing)};${e.textTransform ? `\n  text-transform: ${e.textTransform};` : ''}${e.textDecoration ? `\n  text-decoration: ${e.textDecoration};` : ''}\n}\n`;
}
css += typeCss + '\n' + scaleCss;

// ---------- 3. TypeScript ----------
const nest = (rows, pick) => {
  const o = {};
  for (const r of rows) {
    let cur = o;
    r.path.slice(0, -1).forEach((k) => (cur = cur[k] ??= {}));
    cur[r.path.at(-1)] = pick(r);
  }
  return o;
};
const ref = themes[0];
const contractRows = contract.tokens.map((p) => ref.byPath.get(p));
const json = (v, ind = 2) => JSON.stringify(v, null, ind);
const indent = (s, n) => s.replace(/\n/g, '\n' + ' '.repeat(n));

const tokenValues = {};
const extensions = {};
const metaOut = {};
for (const th of themes) {
  tokenValues[th.meta.name] = {};
  for (const m of MODES)
    tokenValues[th.meta.name][m] = nest(
      contract.tokens.map((p) => th.byPath.get(p)),
      (t) => t[m].resolved ?? t[m].value,
    );
  extensions[th.meta.name] = Object.fromEntries(th.extensions.map((t) => [t.path.join('.'), `var(${t.cssVariable})`]));
  metaOut[th.meta.name] = { label: th.meta.label, source: th.meta.source, disclaimer: th.meta.disclaimer };
}
const ts =
  banner +
  `\nexport const themeNames = ${json(themes.map((t) => t.meta.name), 0)} as const;\n` +
  `export type ThemeName = (typeof themeNames)[number];\n` +
  `export const modeNames = ${json(MODES, 0)} as const;\n` +
  `export type ModeName = (typeof modeNames)[number];\n\n` +
  `/** Shown wherever a theme is presented. Every theme is an independent interpretation. */\n` +
  `export const themeMeta = ${json(metaOut)} as const;\n\n` +
  `/** Contract tokens as CSS var() references. Identical for every theme, so components never branch on theme. */\n` +
  `export const token = ${json(nest(contractRows, (t) => `var(${t.cssVariable})`))} as const;\n\n` +
  `/** Raw resolved values per theme and mode, for canvas, charts, OG images and anything that cannot read CSS variables. */\n` +
  `export const tokenValues = ${json(tokenValues)} as const;\n\n` +
  `/** Theme-specific extras that sit outside the shared contract. */\n` +
  `export const extensions = ${json(extensions)} as const;\n\n` +
  `/** Font families and role weights per theme (resolved), for next/font setup and non-CSS consumers. */\n` +
  `export const typography = ${json(Object.fromEntries(themes.map((t) => [t.meta.name, t.meta.typography ?? null])))} as const;\n\n` +
  `/** Type scale, theme independent. Class names are .bricks-text-{group}-{step}. */\n` +
  `export const typeScale = ${json(scale)} as const;\n`;

// ---------- 4. Tailwind v4 (optional) ----------
const tw =
  banner +
  `/* Optional. Import only if the site uses Tailwind v4. Utilities: bg-background-base, text-content-default, border-border-default ... */\n` +
  `@theme inline {\n` +
  contractRows
    .filter((t) => !String(t.light.value).startsWith('linear-gradient'))
    .map((t) => `  --color-${t.cssVariable.slice(prefix.length)}: var(${t.cssVariable});`)
    .join('\n') +
  `\n  --background-image-brand-gradient: var(${prefix}brand-gradient);\n}\n`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'bricks.tokens.css'), css);
fs.writeFileSync(path.join(outDir, 'bricks.tokens.ts'), ts);
fs.writeFileSync(path.join(outDir, 'bricks.tailwind.css'), tw);

// ---------- 5. Contrast report ----------
const hex = (s) => {
  const h = String(s).replace('#', '');
  return h.length === 6 ? [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255) : null;
};
const lum = (rgb) => {
  const [r, g, b] = rgb.map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
const pairs = [];
const text = (fg, bg) => pairs.push([fg, bg, 4.5, 'text']);
for (const bg of ['background.base', 'background.surface', 'background.layer', 'background.hover']) text('content.default', bg);
for (const bg of ['background.base', 'background.surface', 'background.layer']) text('content.subtle', bg);
text('content.strong', 'background.surface');
for (const bg of ['background.primary', 'background.active', 'background.secondary', 'background.promotional', 'status.positive.backgroundDefault', 'status.critical.backgroundDefault', 'status.warning.backgroundDefault', 'status.alert.backgroundDefault', 'status.info.backgroundDefault', 'status.neutral.backgroundDefault'])
  text('content.onDark', bg);
for (const bg of ['background.base', 'background.surface']) text('link.defaultBase', bg);
for (const s of ['positive', 'critical', 'warning', 'alert', 'info']) text(`status.${s}.contentAccent`, `status.${s}.backgroundSubtle`);
pairs.push(['border.default', 'background.surface', 3, 'ui'], ['border.active', 'background.surface', 3, 'ui'], ['background.secondary', 'background.base', 1.2, 'distinct']);

const lines = ['# BRICKS contrast report (WCAG 2.x)', '', 'Generated by build-tokens.mjs. Only pairs where both colours are opaque are checked.', ''];
let fails = 0;
for (const th of themes) {
  for (const m of MODES) {
    lines.push(`## ${th.meta.name} / ${m}`, '', '| Foreground | Background | Ratio | Needs | Result |', '|---|---|---|---|---|');
    for (const [fg, bg, min, kind] of pairs) {
      const a = th.byPath.get(fg)?.[m];
      const b = th.byPath.get(bg)?.[m];
      const ra = a && hex(a.resolved ?? a.value);
      const rb = b && hex(b.resolved ?? b.value);
      if (!ra || !rb) continue;
      const r = ratio(ra, rb);
      const ok = r >= min;
      if (!ok) fails++;
      lines.push(`| ${fg} | ${bg} | ${r.toFixed(2)} | ${min} (${kind}) | ${ok ? 'pass' : 'FAIL'} |`);
    }
    lines.push('');
  }
}
fs.writeFileSync(path.join(outDir, 'contrast-report.md'), lines.join('\n'));

console.log(`BRICKS: ${themes.length} theme(s) [${themes.map((t) => t.meta.name).join(', ')}], ${contract.tokens.length} contract tokens, ${MODES.length} modes.`);
console.log(`Wrote CSS, TS, Tailwind and contrast report to ${path.relative(process.cwd(), outDir) || outDir} (${fails} contrast failures flagged).`);
